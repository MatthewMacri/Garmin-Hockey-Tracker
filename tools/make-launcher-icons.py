#!/usr/bin/env python3
"""Draw the launcher icon at every size the supported watches ask for.

Garmin devices want launcher icons in twenty different sizes, from 26x26 to
70x70. Shipping one bitmap means the compiler rescales it for almost every
watch, which is both a warning per device and a visibly soft icon on half of
them. So render it once per size instead, and generate the jungle lines that
point each device at the right one.

    python3 tools/make-launcher-icons.py

Rewrites IndoorHockey/resources-icon-<W>x<H>/ and IndoorHockey/icons.jungle.
Re-run it after adding devices to the manifest.
"""

import json
import os
import re
import shutil
import sys

try:
    from PIL import Image, ImageDraw
except ImportError:
    sys.exit("needs Pillow: pip install --user Pillow")

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(os.path.dirname(HERE), "IndoorHockey")
DEVICES = os.path.expanduser("~/.Garmin/ConnectIQ/Devices")

SUPERSAMPLE = 8


def draw(width, height):
    """A puck inside the shift ring, which is the app's own signature.

    The ring is what the watch face draws around the edge while a shift runs,
    so the icon and the running app share a mark. The gap at the bottom keeps
    it from reading as a plain record button.

    Two things constrain the drawing, and both are about 26x26, the smallest
    size any supported watch asks for. There is no interior detail, because at
    26px it turns to mush. And the puck is dark with a pale rim rather than the
    pale body it used to have: a light shape reads on the dark background of an
    app list and disappears on a light one, while a dark shape with a rim reads
    on either.
    """
    w, h = width * SUPERSAMPLE, height * SUPERSAMPLE
    n = min(w, h)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    cx, cy = w // 2, h // 2

    GREEN = (0, 200, 120, 255)
    BODY = (26, 28, 33, 255)
    RIM = (205, 214, 224, 255)

    # The ring, drawn as an arc with a gap at the bottom.
    ring = max(SUPERSAMPLE, int(n * 0.13))
    pad = int(n * 0.055) + ring // 2
    d.arc([cx - n // 2 + pad, cy - n // 2 + pad, cx + n // 2 - pad, cy + n // 2 - pad],
          -215, 35, fill=GREEN, width=ring)

    # The puck, seen from above.
    r = int(n * 0.27)
    d.ellipse([cx - r, cy - r, cx + r, cy + r],
              fill=BODY, outline=RIM, width=max(SUPERSAMPLE, int(n * 0.035)))

    return img.resize((width, height), Image.LANCZOS)


def icon_size(device):
    path = os.path.join(DEVICES, device, "compiler.json")
    if not os.path.exists(path):
        return None
    with open(path) as fh:
        spec = json.load(fh).get("launcherIcon") or {}
    w, h = spec.get("width"), spec.get("height")
    return (w, h) if w and h else None


def main():
    manifest = open(os.path.join(APP, "manifest.xml")).read()
    products = re.findall(r'<iq:product id="([^"]+)"', manifest)
    if not products:
        sys.exit("no products in manifest.xml")

    wanted = {}
    missing = []
    for device in products:
        size = icon_size(device)
        if size is None:
            missing.append(device)
        else:
            wanted.setdefault(size, []).append(device)

    for stale in os.listdir(APP):
        if stale.startswith("resources-icon-"):
            shutil.rmtree(os.path.join(APP, stale))

    lines = ["# Generated by tools/make-launcher-icons.py - do not edit by hand.",
             "# Points each device at a launcher icon drawn at its own size.", ""]
    for (w, h), devices in sorted(wanted.items()):
        folder = "resources-icon-%dx%d" % (w, h)
        target = os.path.join(APP, folder, "drawables")
        os.makedirs(target)
        draw(w, h).save(os.path.join(target, "launcher_icon.png"))
        with open(os.path.join(target, "drawables.xml"), "w") as fh:
            fh.write('<drawables>\n'
                     '    <bitmap id="LauncherIcon" filename="launcher_icon.png" />\n'
                     '</drawables>\n')
        for device in sorted(devices):
            lines.append("%s.resourcePath = $(%s.resourcePath);%s" % (device, device, folder))
        lines.append("")

    with open(os.path.join(APP, "icons.jungle"), "w") as fh:
        fh.write("\n".join(lines))

    # The fallback the manifest points at, used by any device without a folder
    # of its own above. It was drawn by hand once and then never updated, so it
    # went on shipping the previous mark after this script changed; writing it
    # here means the two cannot drift apart again.
    base = os.path.join(APP, "resources", "drawables", "launcher_icon.png")
    draw(60, 60).save(base)

    print("%d sizes for %d devices" % (len(wanted), len(products) - len(missing)))
    if missing:
        print("no device files installed for: %s" % ", ".join(missing))


if __name__ == "__main__":
    main()
